// Generate only the program-independent builtin environment displayed by the
// pinned Gleam generic inspector. Runtime frames and values remain native.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const oracle = resolve(process.env.EYG_ORACLE_ROOT || resolve(packageRoot, '../../work/oracle-next-tui'));
const sha = execFileSync('git', ['rev-parse', 'HEAD'], { cwd: oracle, encoding: 'utf8' }).trim();
if (sha !== 'be502aa03df926a8f9df474a0a7fe16c8fb14fbd') throw new Error(`Unexpected oracle revision ${sha}`);
const build = resolve(oracle, 'packages/gleam_cli/build/dev/javascript');
const load = path => import(pathToFileURL(resolve(build, path)).href);
const [builtins, runtime, string] = await Promise.all([
  load('eyg_interpreter/eyg/interpreter/builtin.mjs'),
  load('eyg_interpreter/gleam.mjs'),
  load('gleam_stdlib/gleam/string.mjs'),
]);
const text = string.inspect(builtins.default$(runtime.List$Empty$const).builtins);
const manifest = await readFile(resolve(oracle, 'packages/gleam_cli/manifest.toml'));
const manifestHash = createHash('sha256').update(manifest).digest('hex');
const hashFile = async path => createHash('sha256').update(await readFile(path)).digest('hex');
const [generatorHash, builtinHash, inspectorHash] = await Promise.all([
  hashFile(fileURLToPath(import.meta.url)),
  hashFile(resolve(build, 'eyg_interpreter/eyg/interpreter/builtin.mjs')),
  hashFile(resolve(build, 'gleam_stdlib/gleam_stdlib.mjs')),
]);
const output = `//! Generated by scripts/generate_inspector.mjs from the actual pinned oracle.\n` +
  `pub const oracle = ${JSON.stringify(sha)};\n` +
  `pub const manifest_sha256 = ${JSON.stringify(manifestHash)};\n` +
  `pub const generator_sha256 = ${JSON.stringify(generatorHash)};\n` +
  `pub const builtin_module_sha256 = ${JSON.stringify(builtinHash)};\n` +
  `pub const inspector_module_sha256 = ${JSON.stringify(inspectorHash)};\n` +
  `pub const builtins = ${JSON.stringify(text)};\n`;
await writeFile(resolve(packageRoot, 'src/generated_builtins_inspect.zig'), output);
console.log(JSON.stringify({ oracle: sha, manifest_sha256: manifestHash, bytes: text.length }));
