"""Rebuild Unicode 16 tables. Requires regex==2024.11.6 and ICU 76.

Only development uses Python/ICU; the interpreter has no Unicode shared-library
or Python runtime dependency. The generated data are derived from Unicode data
(https://www.unicode.org/license.txt).
"""
import array, ctypes, ctypes.util, pathlib, re, importlib.metadata
import regex
assert importlib.metadata.version("regex") == "2024.11.6", "requires regex==2024.11.6 (Unicode16)"
root = pathlib.Path(__file__).resolve().parents[1]
text = ''.join(map(chr, range(0x110000)))
props = array.array('H', [0]) * len(text)
names = ['CR','LF','Control','Extend','ZWJ','Regional_Indicator','Prepend','SpacingMark','L','V','T','LV','LVT']
for n,name in enumerate(names,1):
 for match in regex.finditer(r'\p{gcb='+name+r'}+', text):
  props[match.start():match.end()] = array.array('H',[n]) * (match.end()-match.start())
for name,bit in [('Extended_Pictographic',32),('InCB=Consonant',64),('InCB=Linker',128),('InCB=Extend',256),('Cased',512),('Case_Ignorable',1024)]:
 for match in regex.finditer(r'\p{'+name+r'}+',text):
  for i in range(match.start(),match.end()): props[i] |= bit
ranges=[]
i=0
while i<len(props):
 j=i+1
 while j<len(props) and props[j]==props[i]:j+=1
 if props[i]: ranges.append((i,j-1,props[i]))
 i=j
libname = ctypes.util.find_library('icuuc')
lib = ctypes.CDLL(libname)
version = re.search(r'\.so\.(\d+)',libname).group(1)
assert version == "76", "requires ICU76 (Unicode16)"
case=[]
for upper in [False,True]:
 func=getattr(lib,('u_strToUpper_' if upper else 'u_strToLower_')+version)
 func.restype=ctypes.c_int32
 func.argtypes=[ctypes.POINTER(ctypes.c_uint16),ctypes.c_int32,ctypes.POINTER(ctypes.c_uint16),ctypes.c_int32,ctypes.c_char_p,ctypes.POINTER(ctypes.c_int32)]
 entries=[]
 for cp in range(0x110000):
  if 0xd800<=cp<=0xdfff:continue
  ch=chr(cp); raw=ch.encode('utf-16-le'); source=(ctypes.c_uint16*(len(raw)//2)).from_buffer_copy(raw)
  output=(ctypes.c_uint16*16)(); error=ctypes.c_int32(0)
  length=func(output,16,source,len(source),b'',ctypes.byref(error))
  result=bytes(output)[:length*2].decode('utf-16-le')
  if result!=ch: entries.append((cp,result))
 case.append(entries)
def zstr(s):return '"'+''.join('\\x%02x'%b for b in s.encode())+'"'
with (root/'src/unicode_data.zig').open('w') as f:
 f.write('// Generated by scripts/generate_unicode.py; Unicode 16, ICU 76.\n')
 f.write('pub const ranges = [_]struct {first:u21,last:u21,flags:u16}{\n')
 for a,b,n in ranges:f.write('    .{.first=0x%x,.last=0x%x,.flags=%d},\n'%(a,b,n))
 f.write('};\n')
 for name,entries in zip(['lower','upper'],case):
  f.write('pub const '+name+' = [_]struct {cp:u21,text:[]const u8}{\n')
  for cp,s in entries:f.write('    .{.cp=0x%x,.text=%s},\n'%(cp,zstr(s)))
  f.write('};\n')
print(len(ranges),*[len(a) for a in case])
