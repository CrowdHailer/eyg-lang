#!/usr/bin/env python3
"""Publish complete, verifiable source listings and reconstruct their build tree."""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import re


ROOT = Path(__file__).resolve().parents[1]
LISTINGS = ROOT / "docs" / "source-listings.md"
SKIP = {".git", ".zig-cache", "zig-out", "node_modules", "build", ".gradle", "__pycache__", ".cxx", ".expo", "dist", "reports", "artifacts", "work"}
SUFFIXES = {
    ".zig", ".zon", ".py", ".mjs", ".js", ".ts", ".tsx", ".json", ".gleam", ".eyg",
    ".toml", ".sh", ".gradle", ".kts", ".kt", ".xml", ".properties", ".bat", ".c", ".h", ".cpp", ".java", ".pro", ".txt", ".md",
}
LANGUAGES = {".zig": "zig", ".py": "python", ".mjs": "javascript", ".js": "javascript",
             ".ts": "typescript", ".tsx": "tsx", ".sh": "sh", ".json": "json",
             ".xml": "xml", ".kts": "kotlin", ".c": "c", ".h": "c", ".eyg": "eyg"}


def source_paths() -> list[Path]:
    paths = [ROOT / "build.zig", ROOT / "build.zig.zon", ROOT / "README.md", Path(__file__).resolve()]
    for directory in ("src", "tools", "scripts", "tests", "git", "http", "android"):
        start = ROOT / directory
        if not start.exists():
            continue
        for directory_path, directories, files in os.walk(start):
            directories[:] = [name for name in directories if name not in SKIP]
            for name in files:
                if name in {"local.properties", "validation.json", "native-libraries.json", "native-benchmark.json", "native-benchmark-loaded.json"}:
                    continue
                path = Path(directory_path) / name
                if path.suffix in SUFFIXES or name in {"Makefile", "gradlew", "CMakeLists.txt", "zig", "verify"}:
                    paths.append(path)
    repository = ROOT.parent.parent
    fixtures = repository / "spec" / "evaluation"
    if fixtures.exists():
        paths.extend(fixtures.glob("*.json"))
    paths.append(repository / "LICENSE")
    return sorted({path for path in paths if path.is_file()})


def render() -> str:
    sections = [
        "# Crafting an EYG interpreter: complete source listings\n\n",
        "Generated by `python3 docs/book_sources.py`; do not edit this appendix.\n",
        "Each listing contains the exact UTF-8 bytes of its canonical file.\n",
        "From the package directory, reconstruct a separate build with\n",
        "`python3 docs/book_sources.py --extract ../../work/book-example`.\n",
        "The export includes `packages/zig_runtime/` and upstream evaluation fixtures\n",
        "under `spec/evaluation/`, so its unit tests have the same inputs.\n\n",
    ]
    for path in source_paths():
        data = path.read_bytes()
        source = data.decode("utf-8")
        name = path.relative_to(ROOT.parent.parent).as_posix()
        metadata = {"path": name, "sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data)}
        fence = "`" * max(3, max((len(m.group()) + 1 for m in re.finditer(r"`+", source)), default=3))
        sections.extend([
            f"## `{name}`\n\n",
            "<!-- eyg-source: " + json.dumps(metadata, separators=(",", ":")) + " -->\n",
            fence + LANGUAGES.get(path.suffix, "text") + "\n",
            source,
            "" if source.endswith("\n") else "\n",
            fence + "\n\n",
        ])
    return "".join(sections)


def extract(destination: Path) -> int:
    document = LISTINGS.read_bytes().decode("utf-8")
    pattern = re.compile(r"^<!-- eyg-source: (.+) -->\n(`{3,})[^\n]*\n", re.MULTILINE)
    count = 0
    for match in pattern.finditer(document):
        metadata = json.loads(match[1])
        relative = PurePosixPath(metadata["path"])
        if relative.is_absolute() or ".." in relative.parts or not relative.parts:
            raise ValueError(f"Invalid source path: {relative}")
        closing = document.find("\n" + match[2] + "\n", match.end())
        if closing < 0:
            raise ValueError(f"Missing closing fence: {relative}")
        data = (document[match.end():closing] + "\n").encode("utf-8")[:metadata["bytes"]]
        if len(data) != metadata["bytes"] or hashlib.sha256(data).hexdigest() != metadata["sha256"]:
            raise ValueError(f"Source hash mismatch: {relative}")
        target = destination.joinpath(*relative.parts)
        if any(parent.is_symlink() for parent in (target, *target.parents)):
            raise ValueError(f"Refusing symlink destination: {target}")
        target.parent.mkdir(parents=True, exist_ok=True)
        if target.exists() and target.read_bytes() != data:
            raise ValueError(f"Refusing to overwrite a different file: {target}")
        target.write_bytes(data)
        if target.name in {"gradlew", "zig", "verify"} or target.suffix == ".sh":
            target.chmod(target.stat().st_mode | 0o111)
        count += 1
    if count == 0:
        raise ValueError("The appendix contains no source listings")
    return count


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if canonical files differ from the appendix")
    parser.add_argument("--extract", type=Path, metavar="DIRECTORY", help="reconstruct package sources from the appendix")
    arguments = parser.parse_args()
    if arguments.extract:
        count = extract(arguments.extract)
        print(f"Reconstructed {count} verified source files in {arguments.extract}")
    elif arguments.check:
        if not LISTINGS.exists() or LISTINGS.read_bytes().decode("utf-8") != render():
            parser.exit(1, "Source appendix is stale; run python3 docs/book_sources.py\n")
        print("Source appendix matches canonical files")
    else:
        LISTINGS.write_text(render(), encoding="utf-8")
        print(f"Wrote {LISTINGS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
